"""
Market data loader for CMS option markets.

Attempts to load data from a live API. Falls back to synthetic data
if the API is unavailable or does not carry CMS-specific products.

CMS option data requires a specialised interest-rate data provider.
Equity-focused APIs (e.g. Massive) do not carry CMS rate options, so
the fallback to the :class:`~src.market_data.SyntheticCMSMarket`
generator is the expected production path.
"""
from __future__ import annotations

from typing import Any, Dict


def load_cms_market_data(
    scenario: str = "2s20s",
    expiry_years: float = 5.0,
    stressed: bool = False,
    use_synthetic: bool = True,
) -> Dict[str, Any]:
    """Load CMS market data for the requested scenario.

    Real CMS option data is not available via general-purpose market-data
    APIs (which are primarily equity-focused).  This function therefore
    always returns **synthetic** data generated by
    :class:`~src.market_data.SyntheticCMSMarket`.

    Parameters
    ----------
    scenario : str
        ``'2s20s'`` (CMS20y / CMS2y spread) or ``'30y2y'``
        (CMS30y / CMS2y spread).
    expiry_years : float
        Option expiry in years (default 5.0).
    stressed : bool
        When *True*, apply stressed vol parameters.
    use_synthetic : bool
        Reserved for future use; currently always *True*.

    Returns
    -------
    dict
        Market data bundle with additional meta-data keys
        ``'source'``, ``'scenario'``, and ``'note'``.
    """
    from src.market_data import SyntheticCMSMarket

    market = SyntheticCMSMarket(
        scenario=scenario,
        expiry_years=expiry_years,
        stressed=stressed,
    )
    data: Dict[str, Any] = market.get_market_data()
    data["source"] = "synthetic"
    data["scenario"] = scenario
    data["note"] = (
        "CMS option data generated synthetically via the Bachelier model "
        "with a quadratic smile.  Real CMS data requires a specialised "
        "IR data provider not available through general-purpose market APIs."
    )
    return data
